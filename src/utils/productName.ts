/**
 * الاسم المعروض للمنتج.
 *
 * `model` حقل قديم مكرّر للاسم، كانت النشرة تعرضه بينما تعرض صفحة المنتجات
 * `name` — فينفصل الاسمان. الآن كل حفظ يكتب في `name` ويفرّغ `model`،
 * وهذه الدالة هي مسار القراءة الوحيد الذي يجسر البيانات القديمة.
 *
 * بعد تفريغ `model` لكل الصفوف في قاعدة البيانات تصبح هذه الدالة بلا أثر
 * ويمكن حذفها واستبدالها بـ `p.name` مباشرة.
 */
export function productDisplayName(p: {
  name: string;
  model?: string | null;
}): string {
  return p.model?.trim() || p.name.trim();
}
